def build_prices(start_yr, end_yr, msrp_start, dealer_start, dealer_end, msrp_end=None):
    """線性插值產生歷年 MSRP、車商認證價、民間自售價、天書收購價"""
    if msrp_end is None:
        msrp_end = msrp_start
    years = list(range(start_yr, end_yr + 1))
    n = max(1, len(years) - 1)
    out = {}
    for i, yr in enumerate(years):
        t = i / n if len(years) > 1 else 1.0
        msrp = round(msrp_start + (msrp_end - msrp_start) * t, 1)
        dealer = round(dealer_start + (dealer_end - dealer_start) * t, 1)
        private = round(max(3.5, dealer * 0.89 - (1.0 if dealer > 40 else 0.4)), 1)
        book = round(max(2.5, dealer * 0.78 - (1.2 if dealer > 40 else 0.5)), 1)
        out[str(yr)] = {
            "msrp": msrp,
            "dealer": dealer,
            "private": private,
            "book": book,
        }
    return out


def make_trim(
    trim_name,
    msrp_wan,
    engine_code,
    cc,
    hp,
    torque,
    trans,
    drive,
    susp,
    fuel,
    dims,
    safety,
):
    return {
        "trim_name": trim_name,
        "msrp_wan": msrp_wan,
        "engine_code": engine_code,
        "displacement_cc": cc,
        "horsepower": hp,
        "torque": torque,
        "transmission": trans,
        "drivetrain": drive,
        "suspension": susp,
        "fuel_economy": fuel,
        "dimensions": dims,
        "safety": safety,
    }


def make_gen(
    gen_id,
    gen_name,
    start_yr,
    end_yr,
    major_note,
    platform,
    origin,
    photo_query,
    visual_cues,
    body_style,
    alert_level,
    alert_title,
    alert_reason,
    trims,
    issues,
    prices,
    is_major=True,
):
    return {
        "gen_id": gen_id,
        "gen_name": gen_name,
        "years": list(range(start_yr, end_yr + 1)),
        "is_major_change": is_major,
        "major_change_year": start_yr,
        "major_change_note": major_note,
        "platform": platform,
        "origin": origin,
        "photo_query": photo_query,
        "photo_spec": {
            "expected_filename": f"assets/cars/{gen_id}.jpg",
            "dimensions": "640x420",
            "background": "#FFFFFF (純白背景去背，車輛置中占畫面約 80%-85%)",
            "angle": "前斜側 45 度 (Front 3/4 view) 為佳，車頭朝左或朝右皆可",
            "body_style": body_style,
            "visual_cues": visual_cues,
        },
        "depreciation_alert": {
            "level": alert_level,
            "title": alert_title,
            "reason": alert_reason,
        },
        "trims": trims,
        "common_issues": issues,
        "yearly_prices": prices,
    }


