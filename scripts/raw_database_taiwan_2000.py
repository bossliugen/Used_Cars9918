from raw_database_catalog import build_prices, make_trim, make_gen, make_car, issue


def _quick_car(
    cid, brand, model, model_zh, category, summary,
    gen_id, gen_name, y1, y2, origin, msrp, cc, hp, torque, trans, drive, fuel,
    alert_lvl, alert_title, alert_reason, issue_title, issue_risk, issue_cost,
    p_start, p_end
):
    """快速建立標準單世代或多世代代表車款"""
    return make_car(
        cid, brand, model, model_zh, category, summary,
        [
            make_gen(
                gen_id, gen_name, y1, y2,
                summary,
                f"{brand} 原廠平台", origin,
                f"{brand} {model} {y1}-{y2} Taiwan",
                f"{brand} {model} 台灣市售規格外觀", category,
                alert_lvl, alert_title, alert_reason,
                [make_trim(
                    f"{model} 主力規格", msrp, f"{brand} {model} 動力系統",
                    cc, hp, torque, trans, drive,
                    "前麥花臣 / 後獨立多連桿或扭力樑", fuel,
                    "依各年式原廠規格", "ABS、循跡防滑、多具安全氣囊"
                )],
                [issue(issue_title, issue_risk, "依車齡與里程檢查",
                       f"{model} 常見耗材老化或電子系統檢查重點。",
                       "購車前建議頂高檢查底盤與電腦診斷", issue_cost)],
                build_prices(y1, y2, msrp * 0.85, p_start, p_end, msrp),
            )
        ],
    )


