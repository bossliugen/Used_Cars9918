def _build_all():
    cars = []
    for row in _NEW_BRAND_SPECS + _EXISTING_BRAND_ADDONS:
        (
            cid, brand, model, model_zh, category, summary,
            gen_id, gen_name, y1, y2, origin, msrp, cc, hp, torque, trans, drive, fuel,
            alert_lvl, alert_title, alert_reason, issue_title, issue_risk, issue_cost
        ) = row
        # 依車齡自動推算合理的二手價格帶 (萬元)
        age_oldest = max(1, 2026 - y1)
        age_newest = max(1, 2026 - y2)
        retention_oldest = max(0.08, 0.90 - age_oldest * 0.055 if age_oldest <= 10 else 0.35 - (age_oldest - 10) * 0.022)
        retention_newest = max(0.15, 0.92 - age_newest * 0.055 if age_newest <= 10 else 0.37 - (age_newest - 10) * 0.022)
        p_start = round(max(4.5, msrp * retention_oldest), 1)
        p_end = round(max(p_start + 1.0, msrp * retention_newest), 1)
        if p_end > msrp * 0.96:
            p_end = round(msrp * 0.94, 1)
        if p_start >= p_end:
            p_start = round(max(3.5, p_end * 0.55), 1)

        cars.append(_quick_car(
            cid, brand, model, model_zh, category, summary,
            gen_id, gen_name, y1, y2, origin, msrp, cc, hp, torque, trans, drive, fuel,
            alert_lvl, alert_title, alert_reason, issue_title, issue_risk, issue_cost,
            p_start, p_end
        ))
    return cars


TAIWAN_2000_CARS = _build_all()
